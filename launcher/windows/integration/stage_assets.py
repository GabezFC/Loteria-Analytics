"""Generate Windows package assets from the canonical Compose and PostgreSQL files."""
import argparse
from pathlib import Path

CANONICAL = Path(__file__).resolve().parents[3]
APP = Path(__file__).resolve().parents[1] / 'app'
OWNER_LABEL = 'io.cassino.launcher.owner'
LABEL = f'      {OWNER_LABEL}: ${{CASSINO_LAUNCHER_OWNER:?}}\n'
LOCAL_IMAGES = {name: f'cassino-launcher/{name}:0.1.0-local' for name in ('backend', 'frontend', 'workers')}
HEADER = '# Generated by launcher/windows/integration/stage_assets.py; do not edit.\n'


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f'Canonical Compose changed; expected exactly one occurrence of {old.strip()!r}.')
    return text.replace(old, new, 1)


def stage(destination):
    main = (CANONICAL / 'compose.yaml').read_text(encoding='utf-8')
    admin = (CANONICAL / 'infra/portainer/compose.yaml').read_text(encoding='utf-8')
    main = replace_once(main, 'name: cassino\n', 'name: cassino-launcher\n')
    admin = replace_once(admin, 'name: cassino-admin\n', 'name: cassino-launcher-admin\n')
    for component, image in LOCAL_IMAGES.items():
        main = replace_once(main, f'    build: ./{component}\n',
                            f'    image: ${{CASSINO_{component.upper()}_IMAGE:-{image}}}\n'
                            '    pull_policy: never\n')
    for key, port, target in [('APP', 3000, 80), ('CLOUDBEAVER', 8978, 8978)]:
        main = replace_once(main, f'127.0.0.1:{port}:{target}',
                            f'127.0.0.1:${{CASSINO_{key}_PORT:-{port}}}:{target}')
    admin = replace_once(admin, '127.0.0.1:9443:9443',
                         '127.0.0.1:${CASSINO_PORTAINER_PORT:-9443}:9443')
    main = replace_once(main, '  restart: unless-stopped\n',
                        '  restart: unless-stopped\n  labels:\n' + LABEL[2:])
    admin = replace_once(admin, '    restart: unless-stopped\n',
                         '    restart: unless-stopped\n    labels:\n' + LABEL)
    default = '  default:\n    name: ${COMPOSE_PROJECT_NAME}_default\n    driver: bridge\n    labels:\n' + LABEL
    main = replace_once(main, '  default:\n    driver: bridge\n', default)
    admin = replace_once(admin, '\nvolumes:\n', '\nnetworks:\n' + default + 'volumes:\n')
    for name in ('postgres_data', 'cloudbeaver_workspace'):
        main = replace_once(main, f'  {name}:\n',
                            f'  {name}:\n    name: ${{COMPOSE_PROJECT_NAME}}_{name}\n    labels:\n' + LABEL)
    admin = replace_once(admin, '  portainer_data:\n',
                         '  portainer_data:\n    name: ${COMPOSE_PROJECT_NAME}_portainer_data\n    labels:\n' + LABEL)
    # Fail fast on a partial bundle; ship only canonical migration files and the base shell script.
    source = CANONICAL / 'infra/postgres'
    migrations = sorted(source.glob('*.sql'))
    if [p.name.split('-', 1)[0] for p in migrations] != ['002', '003', '004', '005', '006']:
        raise ValueError('Expected one canonical SQL file per migration 002–006; update the Core and staging together.')
    base = (source / '001-base.sh').read_bytes()
    if b'\r' in base or not base.startswith(b'#!/bin/sh\n'):
        raise ValueError('Canonical PostgreSQL init script must be POSIX shell with LF line endings.')
    payload = {Path('compose.yaml'): (HEADER + main).encode('utf-8'),
               Path('compose.admin.yaml'): (HEADER + admin).encode('utf-8'),
               Path('infra/postgres/001-base.sh'): base}
    lan = APP.parent / 'lan'
    for name in ('compose.local.yaml', 'compose.lan.yaml', 'local.conf', 'proxy.inc', 'tls.conf.template', 'bootstrap.py', 'README.md'):
        payload[Path('lan') / name] = (lan / name).read_bytes()
    for migration in migrations:
        payload[Path('infra/postgres') / migration.name] = migration.read_bytes()
    pg = destination / 'infra/postgres'
    extra = {p for p in pg.glob('*.sql') if Path('infra/postgres') / p.name not in payload}
    if extra:
        raise ValueError('Destination contains stale SQL; stage into a clean app directory.')
    for relative, data in payload.items():
        path = destination / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=APP, help='Asset directory (default: launcher/windows/app)')
    args = parser.parse_args()
    stage(args.output.resolve())
    print(f'Staged Windows Compose and PostgreSQL assets in {args.output.resolve()}')
